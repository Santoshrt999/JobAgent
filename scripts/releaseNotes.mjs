#!/usr/bin/env node
/**
 * One source for release notes: src/dashboard/public/assets/js/changelog-data.js
 * (the in-app changelog). This script turns it into
 *
 *   --changelog        CHANGELOG.md at the repository root (committed; a test
 *                      keeps it identical to the in-app data)
 *   --notes <vX.Y.Z>   the GitHub release notes for one tagged version, after
 *                      checking the tag, package.json and the changelog agree
 *
 * Usage:
 *   node scripts/releaseNotes.mjs --changelog
 *   node scripts/releaseNotes.mjs --notes v0.2.0 > notes.md
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

import { CHANGELOG, CHANGELOG_GROUPS } from '../src/dashboard/public/assets/js/changelog-data.js';

const ROOT = new URL('../', import.meta.url);

/** One release as Markdown, headed at the given level. */
export function releaseMarkdown(release, { heading = '##' } = {}) {
  const title = release.version ? `${release.version} (${release.date})` : release.date;
  const lines = [`${heading} ${title}`, ''];
  if (release.summary) lines.push(release.summary, '');
  for (const [key, label] of CHANGELOG_GROUPS) {
    const items = release.groups?.[key] ?? [];
    if (!items.length) continue;
    lines.push(`${heading}# ${label}`, '');
    for (const item of items) lines.push(`- ${item}`);
    lines.push('');
  }
  if (release.safety) lines.push(`_${release.safety}_`, '');
  return lines.join('\n');
}

/** The whole changelog as Markdown. */
export function changelogMarkdown(releases = CHANGELOG) {
  return [
    '# Changelog',
    '',
    '<!-- Generated by `node scripts/releaseNotes.mjs --changelog` from',
    '     src/dashboard/public/assets/js/changelog-data.js. Edit that file, not this one. -->',
    '',
    ...releases.map((r) => releaseMarkdown(r)),
  ].join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
}

/**
 * The release entry for a tag, or an explanation of why the tag is wrong.
 * @param {string} tag e.g. "v0.2.0"
 * @param {string} packageVersion package.json "version"
 */
export function releaseForTag(tag, packageVersion, releases = CHANGELOG) {
  const version = String(tag ?? '').replace(/^refs\/tags\//, '');
  if (!/^v\d+\.\d+\.\d+$/.test(version)) return { error: `tag "${version}" is not vMAJOR.MINOR.PATCH` };
  if (`v${packageVersion}` !== version) {
    return { error: `tag ${version} does not match package.json version ${packageVersion}` };
  }
  const release = releases.find((r) => r.version === version);
  if (!release) return { error: `no changelog entry has version "${version}"` };
  return { release };
}

function main(argv) {
  if (argv.includes('--changelog')) {
    writeFileSync(new URL('CHANGELOG.md', ROOT), changelogMarkdown());
    console.log('Wrote CHANGELOG.md');
    return;
  }
  const at = argv.indexOf('--notes');
  if (at !== -1) {
    const pkg = JSON.parse(readFileSync(new URL('package.json', ROOT), 'utf8'));
    const { release, error } = releaseForTag(argv[at + 1], pkg.version);
    if (error) {
      console.error(`releaseNotes: ${error}`);
      process.exit(1);
    }
    process.stdout.write(releaseMarkdown(release, { heading: '##' }));
    return;
  }
  console.error('usage: releaseNotes.mjs --changelog | --notes vX.Y.Z');
  process.exit(2);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) main(process.argv.slice(2));
